#include <stdio.h>
#include <stdlib.h>
#include <time.h>

#define MAX_SIZE 100

void uniform(char *str, int len) {
    FILE *fp = fopen(str, "w");
    for (int i = 0; i < len; i++) {
        fprintf(fp, "%lf\n", (double)rand() / RAND_MAX);
    }
    fclose(fp);
}

void randomArrayFromFile(int arr[], int n) { 	//define function to get values from 1 to 100
    double x;
    uniform("random.dat", n);

    FILE *fp = fopen("random.dat", "r");
    for (int i = 0; i < n; i++) {
        fscanf(fp, "%lf", &x);
        // Scale [0.0, 1.0) to an integer [1, 100]
        arr[i] = (int)(x * 100) + 1;
    }
    fclose(fp);
}

int main(void) {
    int arr[MAX_SIZE];
    int n;

    srand(time(NULL));

    // Input validation for array length up to MAX_SIZE
    printf("Enter length of array (1 - %d): ", MAX_SIZE);
    if (scanf("%d", &n) != 1 || n < 1 || n > MAX_SIZE) {
        printf("Invalid input. Length must be between 1 and %d.\n", MAX_SIZE);
        return 1;
    }

    // Populate array with n random values between 1 and 100
    randomArrayFromFile(arr, n);

    printf("\nInitial generated values:\n");
    //printing the initial values generated by RandomArray
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]);
    }
    printf("\n\n");

    // Pointer tracks the minimum value
    int *p = &arr[0];
    for (int i = 1; i < n; i++) {
        if (arr[i] < *p) {
            p = &arr[i];
        }
    }

    // Set minimum to 0 through the pointer
    *p = 0;

    printf("The final values are:\n");
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]);
    }
    printf("\n");

    return 0;
}

